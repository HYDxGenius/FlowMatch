            SSL_Argument('--a1_enable', str2bool, False),
            SSL_Argument('--a2_enable', str2bool, False),
            SSL_Argument('--a3_enable', str2bool, False),
            SSL_Argument('--a3_warmup_iter', int, 20000),
            SSL_Argument('--a3_mix_ratio', float, 0.2),
